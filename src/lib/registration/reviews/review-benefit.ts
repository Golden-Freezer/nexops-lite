/**
 * 후기 문장이 효익으로 끝나는지(2026-11-02, R17-L 후기 카드) — 후기 요약(review-scrubber summarizeReviewSentences)이 먼저 고를 문장을 가린다.
 * 판매 페이지 후기 카드가 산 계기·고민·상황·상품명 줄로 끝나지 않게 하는 선호 기준이다. 막는 규칙이 아니다 — 효익 문장이 없는 글은 예전 기준
 * (처음 쓸 수 있는 문장)대로 실리고, 규제 표현은 이 파일과 상관없이 인용 안전 검사가 본다. 문장을 고치거나 자르지 않는다.
 * 낱말 사전이라 완전하지 않다. 효익을 놓치면 뒤 문장을 고르거나 예전 기준으로 돌아갈 뿐이고, 잘못 집으면 예전처럼 효익 없는 문장이 실린다.
 */

/** 끝 절을 찾는 연결 어미 — 문장 끝의 말만 본다('망설이다가 이 우산으로 바꿨습니다'의 끝 절은 효익이 아니다) */
const CLAUSE_BREAK_RE = /,|는데|지만|다가|려고|어서|아서|해서|여서|려서|보니|더니|니까|으니/

/** 말이 끝나지 않은 꼬리('…무거운 편이고..') — 뒤가 잘린 문장이다. '…튼튼하고요'처럼 요로 끝나면 끝난 말이다 */
const UNFINISHED_RE = /(?:고|며|서|데|지만|니까|면서)\s*[.…~,]*$/

/** 산 계기를 말하는 끝 절 — 앞 절에 효익 낱말이 있어도('깔끔해서 선택했어요') 끝은 구매 이야기다 */
const PURCHASE_TAIL_RE = /구매|구입|선택|주문|바꿨|바꿔|바꾸|장만|들였|골랐|샀|사봤|시켰|찾다|찾아/

/** 문장 어디에 있든 상황 설명으로 보는 말끝 — 뒤따르는 효익 문장을 고른다 */
const SCENE_SETTING_RE = /잖아요|거든요/

/** 바람·부정으로 뒤집히는 말('더 컸으면 좋겠어요'·'좋지 않아요') */
const REVERSED_RE =
  /으?면\s*좋|안\s*(?:돼|되)|(?:좋|(?<!불)편하|예쁘|만족스럽|괜찮|부드럽|시원하|맞|쉽|깔끔하)지\s*(?:않|못)|안\s*좋|별로|그닥|그다지|못\s*(?:쓰|써|사용)/

/** 쓰면서 얻은 좋은 점 — 만족·편함·모양·감촉·수량·문제가 사라진 말 */
const BENEFIT_RE = new RegExp(
  [
    '좋|(?<!불)편[하해한리안]|수월|간편|(?<!아)쉽|(?<!아)쉬[워웠운]',
    '예[쁘뻐]|이[쁘뻐]|귀[엽여]|깜찍|사랑스|깔끔|고급|우아|은은|차분|무난|선명|완성도|정성',
    '시원(?!찮)|개운|부드[럽러]|가[볍벼]|폭신|푹신|튼튼|탄탄|든든|안심|안정',
    '만족|뿌듯|마음에\\s*[들드]|맘에\\s*[들드]|딱이|딱\\s*(?:맞|적당)|적당|넉넉|괜찮|훌륭|탁월|추천',
    '유용|실용|활용도|가성비|가격\\s*대비|윤기|살아나|사라졌|해결|풀[려리어]|줄[었어]|덜하',
    '애용|이것만|매일|꾸준히|쓸\\s*수\\s*있|(?:마다|항상|늘|계속|자주)\\s*(?:써|쓰|씁|사용)',
    '덜\\s*(?:아[프파픈]|불편|엉[키켜]|빠[져지]|번거|힘들)',
    '잘\\s*(?:어울|맞|잡|붙|풀|빗|감|쓰|쓸|써|사용|먹|나[요와옵네]|돼|되|닫|열|보[여이]|들어가|정리|고정|마르|닦|씻)',
    '(?:자극|흔들림|걱정|부담|거부감|스트레스|들뜸|불편)(?:이|가|함)?\\s*(?:없|덜|적|줄)',
    '(?:불편하|아프|떨어지|미끄러지|밀리|엉키|찢어지|끊어지|번들거리|튀|무겁|흔들리|걸리|답답하|부담스럽|촌스럽|유치하|자극적이)지\\s*(?:도\\s*)?않',
    '안\\s*(?:아파|아프|엉켜|엉키|밀려|떨어져|미끄러|찢어|배요|뱁니다|베어)',
  ].join('|')
)

/** 문장의 끝 절이 쓰면서 얻은 좋은 점인지 — 질문·끊긴 꼬리·상황 설명·산 계기로 끝나면 거짓 */
export function endsWithBenefit(sentence: string): boolean {
  const text = (sentence ?? '').trim()
  if (!text || /\?\s*$/.test(text) || UNFINISHED_RE.test(text) || SCENE_SETTING_RE.test(text)) return false
  const clause = text.split(CLAUSE_BREAK_RE).pop() ?? ''
  if (PURCHASE_TAIL_RE.test(clause) || REVERSED_RE.test(clause)) return false
  return BENEFIT_RE.test(clause)
}
