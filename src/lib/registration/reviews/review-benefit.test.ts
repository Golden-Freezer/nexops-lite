/**
 * 후기 문장이 효익으로 끝나는지 — 끝 절만 본다. 지어낸 문장만 쓴다(실제 후기 원문을 넣지 않는다).
 */

import { describe, expect, it } from 'vitest'
import { endsWithBenefit } from './review-benefit'

describe('endsWithBenefit', () => {
  it.each([
    '손잡이가 편해요',
    '거품이 잘 나요.',
    '뭉치던 실이 부드럽게 풀려요.',
    '가방에 넣어도 걱정 없어요.',
    '종일 메도 불편하지 않아요.',
    '이제 안 아파요.',
    '냄새가 안 배요.',
    '짐이 많아 버거웠는데 만족하면서 쓰고 있어요.',
    '값에 비해 가성비 좋은 제품이에요.',
    '처음엔 몰랐는데 이제 이것만 써요.',
    '두 개라서 집과 회사에서 번갈아 쓸 수 있어요.',
    '가격대비 용량이 큽니다.',
    '설거지 스트레스가 많이 줄었어요.',
    '보관도 실용적이고요.',
    '머리 감을 때 손이 덜 아파요.',
    '손이 편해서 아침마다 써요.',
  ])('효익으로 끝난다: %s', (sentence) => {
    expect(endsWithBenefit(sentence)).toBe(true)
  })

  it.each([
    ['상황 설명', '출근길 물병은 고르기 어렵잖아요ㅜㅜ 가벼운 건 또 넘어지고요.'],
    ['상황 설명', '책상이 허전해서 소품을 두고 싶었거든요.'],
    ['산 계기', '뚜껑이 깔끔해 보여 선택했어요.'],
    ['산 계기', '튼튼하기도 하고 망설이다가 이 우산으로 바꿨습니다.'],
    ['산 계기', '단정하면서도 예쁜 컵을 찾다가 이걸 꺼내 봤어요.'],
    ['산 계기', '가벼운 우산으로 바꿨습니다.'],
    ['산 계기', '예쁜 무늬로 골랐어요.'],
    ['고민', '금방 눅눅해져서 쓸 때마다 짜증이 났어요.'],
    ['상황', '베란다가 넓어서 작업실처럼 꾸미고 있습니다.'],
    ['끊긴 꼬리', '물이 잘 빠져요 출근이 잦아서 가방이 무거운 편이고..'],
    ['끊긴 꼬리', '색이 예뻐서..'],
    ['바람', '좋은데 더 컸으면 좋겠어요.'],
    ['부정', '접착력이 좋지 않아요.'],
    ['부정', '끈이 안 좋아요.'],
    ['부정', '해결이 안 돼요.'],
    ['불만 낱말', '손잡이가 불편했어요.'],
    ['불만 낱말', '손잡이가 불편해요.'],
    ['불만 낱말', '크기가 조금 아쉬워요.'],
    ['상품·메타 줄', '퇴근하고 적어 보는 사용기!'],
    ['일반론', '직장인 필수품이 바로 텀블러죠~'],
    ['질문', '이거 정말 좋을까요?'],
    ['빈 글', ''],
  ])('효익으로 끝나지 않는다(%s): %s', (_kind, sentence) => {
    expect(endsWithBenefit(sentence)).toBe(false)
  })

  it('앞 절의 효익 낱말은 세지 않고 끝 절만 본다', () => {
    expect(endsWithBenefit('가벼워서 샀는데 어머니가 쓰고 계세요.')).toBe(false)
    expect(endsWithBenefit('가벼워서 들고 다니다가 어머니께 드렸어요.')).toBe(false)
    expect(endsWithBenefit('머리가 아팠는데 빗고 나면 시원해요.')).toBe(true)
  })
})
